def _name(check_id):
    copy = CONTROL_COPY.get(check_id) or {}
    return copy.get("displayName") or check_id


def _percent(check_id, code, pillar, label, balanced, recommended, strict, help_text):
    return {
        "id": check_id,
        "code": code,
        "name": _name(check_id),
        "pillar": pillar,
        "kind": "percent",
        "pass": "gte",
        "unit": "%",
        "min": 0,
        "max": 100,
        "step": 1,
        "label": label,
        "help": help_text,
        "profiles": {
            "balanced": balanced,
            "recommended": recommended,
            "strict": strict,
        },
    }


def _count(check_id, code, pillar, label, balanced, recommended, strict, help_text,
           pass_dir="lte", unit="", minimum=0, maximum=20, step=1):
    return {
        "id": check_id,
        "code": code,
        "name": _name(check_id),
        "pillar": pillar,
        "kind": "count",
        "pass": pass_dir,
        "unit": unit,
        "min": minimum,
        "max": maximum,
        "step": step,
        "label": label,
        "help": help_text,
        "profiles": {
            "balanced": balanced,
            "recommended": recommended,
            "strict": strict,
        },
    }


def _toggle(check_id, code, pillar, label, balanced, recommended, strict, help_text):
    return {
        "id": check_id,
        "code": code,
        "name": _name(check_id),
        "pillar": pillar,
        "kind": "toggle",
        "pass": "required",
        "label": label,
        "help": help_text,
        "profiles": {
            "balanced": bool(balanced),
            "recommended": bool(recommended),
            "strict": bool(strict),
        },
    }


def _select(check_id, code, pillar, label, options, balanced, recommended, strict, help_text):
    return {
        "id": check_id,
        "code": code,
        "name": _name(check_id),
        "pillar": pillar,
        "kind": "select",
        "pass": "all",
        "options": list(options),
        "label": label,
        "help": help_text,
        "profiles": {
            "balanced": list(balanced),
            "recommended": list(recommended),
            "strict": list(strict),
        },
    }


